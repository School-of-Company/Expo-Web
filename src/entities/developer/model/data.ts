export interface Developer {
  /** 이름 또는 닉네임. 본인이 고른 대로 적는다. */
  name: string;
  /** 담당한 업무 또는 개발한 기능 */
  role: string;
  /** 개발하면서 가장 기억에 남았던 순간은? */
  moment: string;
  /** 개발하면서 어려웠던 점과 해결 과정 */
  challenge: string;
  /** 이번 개발을 통해 느낀 점 */
  takeaway: string;
  /** 깃허브 프로필 URL. 적지 않았으면 비워 둔다. */
  github?: string;
}

export interface DeveloperProject {
  key: string;
  name: string;
  members: Developer[];
}

